class CourseDetails {
  final String title;
  final String subtitle;
  final String weeks;
  final String modules;
  final String price;
  final String image;
  final String status;
  final String level;

  CourseDetails({
    required this.title,
    required this.subtitle,
    required this.weeks,
    required this.modules,
    required this.price,
    required this.image,
    required this.status,
    required this.level,
  });
}